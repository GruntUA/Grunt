"""`grunt app types`: the typed `grunt.call` registry from @grunt.whitelist methods."""

import textwrap
from pathlib import Path

import pytest

from grunt.api import typegen

DEMO = '''
import enum
from dataclasses import dataclass
from typing import Any, Literal, NotRequired, TypedDict

import grunt
from fastapi.responses import FileResponse


class Stats(TypedDict):
    total: int
    by_state: dict[str, int]
    note: NotRequired[str | None]


class Level(enum.StrEnum):
    LOW = "low"
    HIGH = "high"


@dataclass
class Point:
    x: float
    label: str


class Node(TypedDict):
    name: str
    children: list["Node"]


@grunt.whitelist()
async def get_stats(department: str, year: int = 2026, *, request=None) -> Stats:
    """Stats of a department.

    Longer text that is not part of the summary.
    """


@grunt.whitelist(roles=["System Manager"])
async def set_level(level: Level, mode: Literal["a", "b"], points: list[Point]) -> None: ...


@grunt.whitelist(allow_guest=True)
def free_form(name, **kwargs) -> dict[str, Any]: ...


@grunt.whitelist()
async def download(name: str) -> FileResponse: ...


@grunt.whitelist()
def tree() -> Node: ...


def not_exposed(x: int) -> int: ...


class RPCMixin:
    @staticmethod
    @grunt.whitelist()
    async def ping(value: int | None = None) -> bool: ...


class Doc(RPCMixin):
    pass


class SubDoc(Doc):
    pass
'''


@pytest.fixture
def demo(tmp_path, monkeypatch):
    pkg = tmp_path / "tg_demo_app" / "tg_demo_app"
    (pkg / "tests").mkdir(parents=True)
    (pkg / "__init__.py").write_text("")
    (pkg / "api.py").write_text(textwrap.dedent(DEMO))
    (pkg / "plain.py").write_text("def helper():\n    return 1\n")
    # tests/ are never scanned, even with a whitelist in them
    (pkg / "tests" / "test_x.py").write_text("import grunt\n@grunt.whitelist()\ndef t(): ...\n")
    monkeypatch.syspath_prepend(str(tmp_path / "tg_demo_app"))
    return tmp_path / "tg_demo_app"


def _render(app_dir: Path) -> str:
    return typegen.render(
        app_dir.name, typegen.collect_methods(app_dir / app_dir.name, app_dir.name)
    )


def _entry(text: str, path: str) -> str:
    return next(line for line in text.splitlines() if line.strip().startswith(f'"{path}"'))


def test_collects_whitelisted_methods_only(demo):
    paths = [m.path for m in typegen.collect_methods(demo / "tg_demo_app", "tg_demo_app")]
    assert "tg_demo_app.api.get_stats" in paths
    assert "tg_demo_app.api.not_exposed" not in paths
    assert not any(".tests." in p for p in paths)


def test_mixin_methods_exposed_on_direct_subclass(demo):
    paths = {m.path for m in typegen.collect_methods(demo / "tg_demo_app", "tg_demo_app")}
    assert {"tg_demo_app.api.RPCMixin.ping", "tg_demo_app.api.Doc.ping"} <= paths
    # Not on every descendant - that would repeat the method on each DocType.
    assert "tg_demo_app.api.SubDoc.ping" not in paths


def test_render_args_and_named_result(demo):
    text = _render(demo)
    line = _entry(text, "tg_demo_app.api.get_stats")
    # `request` is injected by the dispatcher, a default makes a parameter optional
    assert "args: { department: string; year?: number }" in line
    assert "result: GruntApi.tg_demo_app.Stats" in line
    stats = (
        "interface Stats { total: number; by_state: Record<string, number>; note?: string | null }"
    )
    assert stats in text
    # The docstring's summary paragraph only
    assert "/** Stats of a department. */" in text


def test_render_enum_literal_dataclass_roles(demo):
    text = _render(demo)
    line = _entry(text, "tg_demo_app.api.set_level")
    assert 'mode: "a" | "b"' in line
    assert "level: GruntApi.tg_demo_app.Level" in line
    assert "points: GruntApi.tg_demo_app.Point[]" in line
    assert "result: null" in line
    assert 'type Level = "low" | "high"' in text
    assert "interface Point { x: number; label: string }" in text
    assert "Roles: System Manager." in text


def test_render_untyped_kwargs_response_recursive(demo):
    text = _render(demo)
    free = _entry(text, "tg_demo_app.api.free_form")
    assert "args: { name: any; [key: string]: unknown }" in free
    assert "result: Record<string, any>" in free
    assert "Allowed for guests." in text
    assert "result: unknown" in _entry(text, "tg_demo_app.api.download")
    assert "interface Node { name: string; children: GruntApi.tg_demo_app.Node[] }" in text


def test_generate_writes_then_reports_up_to_date(demo):
    first = typegen.generate(demo)
    assert first.changed and first.path == demo / "tg_demo_app" / "methods.generated.d.ts"
    assert first.path.read_text().startswith("// Generated by `grunt app types`")
    assert not typegen.generate(demo, write=False).changed


def test_app_without_methods_gets_no_file(tmp_path, monkeypatch):
    pkg = tmp_path / "tg_empty_app" / "tg_empty_app"
    pkg.mkdir(parents=True)
    (pkg / "__init__.py").write_text("")
    monkeypatch.syspath_prepend(str(tmp_path / "tg_empty_app"))
    r = typegen.generate(tmp_path / "tg_empty_app")
    assert not r.changed and not r.path.exists()


def test_core_registry_is_up_to_date():
    """Changed a whitelisted method of the core? Run `grunt app types grunt`."""
    core = Path(typegen.__file__).resolve().parents[2]
    assert not typegen.generate(core, write=False).changed, "run: grunt app types grunt"
